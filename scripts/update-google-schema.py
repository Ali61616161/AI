#!/usr/bin/env python3
"""Google Places (New), Weather ve Cloud Translation (v2) API discovery dokümanlarından Yola'nın kullandığı
kısmı supabase/functions/_shared/google/schema.json dosyasına yazar. Testler, Google'a
gönderilen her alanın resmi şemada olduğunu bu dosyayla doğrular.

Kullanım: python3 scripts/update-google-schema.py [places.json weather.json translate.json]
(Dosya verilmezse discovery dokümanları internetten indirilir.)
"""
import json
import sys
import urllib.request

URLS = [
    "https://places.googleapis.com/$discovery/rest?version=v1",
    "https://weather.googleapis.com/$discovery/rest?version=v1",
    "https://translation.googleapis.com/$discovery/rest?version=v2",
]
OUT = "supabase/functions/_shared/google/schema.json"


def load(i):
    if len(sys.argv) > 2:
        with open(sys.argv[1 + i]) as f:
            return json.load(f)
    with urllib.request.urlopen(URLS[i]) as r:
        return json.load(r)


def subset(doc, roots, depth):
    schemas, res = doc["schemas"], {}

    def walk(name, d):
        if name in res or d < 0:
            return
        res[name] = {}
        for key, value in schemas[name].get("properties", {}).items():
            ref = value.get("$ref") or value.get("items", {}).get("$ref")
            enum = value.get("enum") or value.get("items", {}).get("enum")
            res[name][key] = {"enum": enum} if enum else ref
            if ref:
                walk(ref, d - 1)

    for root in roots:
        walk(root, depth)
    return res


def methods(resources, out):
    for res in resources.values():
        for m in res.get("methods", {}).values():
            out[m["path"]] = sorted(m.get("parameters", {}).keys())
        methods(res.get("resources", {}), out)
    return out


places, weather, translate = load(0), load(1), load(2)
out = {
    "_source": "Google API discovery documents: " + ", ".join(URLS) + ". Generated by scripts/update-google-schema.py.",
    "places": {
        "schemas": subset(places, ["GoogleMapsPlacesV1SearchTextRequest", "GoogleMapsPlacesV1SearchTextResponse"], 4),
        "methods": methods(places["resources"], {}),
    },
    "weather": {
        "schemas": subset(weather, ["LookupForecastDaysResponse", "LookupCurrentConditionsResponse"], 4),
        "methods": methods(weather["resources"], {}),
    },
    "translate": {
        "servicePath": translate["servicePath"],
        "schemas": subset(translate, ["TranslateTextRequest", "TranslationsListResponse"], 3),
        "methods": methods(translate["resources"], {}),
    },
}
with open(OUT, "w") as f:
    json.dump(out, f, indent=1, sort_keys=True)
    f.write("\n")
print("wrote", OUT)
